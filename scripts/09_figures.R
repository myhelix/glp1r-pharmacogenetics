###############################################################################
# COMPUTE RESPONSE RATIOS (CARRIER/CONTROL WEIGHT LOSS RATIO)
#
# relative_effect = mean_carrier / mean_control
# Both values are typically negative (weight loss); ratio < 1 = attenuation.
# CI on ratio: (mean_control + ci_lo/hi) / mean_control  (delta method)
###############################################################################

add_relative_effect <- function(df) {
  df %>% mutate(
    relative_effect   = case_when(
      is.na(mean_control) | mean_control >= 0 | is.na(mean_carrier) ~ NA_real_,
      TRUE ~ mean_carrier / mean_control
    ),
    # mean_control < 0, so dividing by it flips the inequality:
    # ci_hi (upper regression CI) maps to the LOWER ratio bound
    # ci_lo (lower regression CI) maps to the UPPER ratio bound
    relative_ci_lower = case_when(
      is.na(mean_control) | mean_control >= 0 ~ NA_real_,
      TRUE ~ pmax((mean_control + ci_hi) / mean_control, 0.01)
    ),
    relative_ci_upper = case_when(
      is.na(mean_control) | mean_control >= 0 ~ NA_real_,
      TRUE ~ pmin((mean_control + ci_lo) / mean_control, 10)
    ),
    ratio_nc = !is.na(mean_carrier) & mean_carrier >= 0
  )
}

all_results <- bind_rows(results_primary, results_subgroup) %>%
  distinct(analysis, .keep_all = TRUE) %>%
  add_relative_effect()


###############################################################################
# FOREST PLOT WITH RESPONSE RATIO AND EMBEDDED TABLE
#
# forest_rows: tibble with columns analysis, display_label, drug_group
#   Rows are ordered bottom-to-top (first row = y=1 = bottom of plot).
#   HEADER_ rows are printed bold; display_label is used for the y-axis tick.
###############################################################################

make_forest_with_table <- function(forest_rows,
                                   color_overall = COLORS$blue,
                                   color_sema    = COLORS$semaglutide,
                                   color_tirz    = COLORS$tirzepatide) {
  x_min      <- 0
  x_max      <- 2.85    # total width including embedded table
  forest_max <- 1.6     # CI clipped at this value
  col_n_x      <- 1.75
  col_weight_x <- 2.20
  col_ratio_x  <- 2.63

  fd <- forest_rows %>%
    left_join(
      all_results %>% select(analysis, n_carriers, n_controls,
                             mean_carrier, mean_control,
                             relative_effect, relative_ci_lower,
                             relative_ci_upper, ratio_nc, ci_lo, ci_hi),
      by = "analysis"
    ) %>%
    mutate(
      is_header  = grepl("^HEADER_", analysis),
      is_primary = display_label == "Any primary coding variant",
      point_color = case_when(
        drug_group == "overall"     ~ color_overall,
        drug_group == "semaglutide" ~ color_sema,
        drug_group == "tirzepatide" ~ color_tirz,
        TRUE ~ "black"
      ),
      col_n = case_when(
        is_header        ~ "",
        is.na(n_carriers) ~ "\u2014",
        TRUE             ~ sprintf("%d/%d", n_carriers, n_controls)
      ),
      col_weight = case_when(
        is_header           ~ "",
        is.na(mean_carrier) ~ "\u2014",
        mean_carrier > 0    ~ sprintf("+%.1f / %.1f",  mean_carrier, mean_control),
        mean_control > 0    ~ sprintf("%.1f / +%.1f",  mean_carrier, mean_control),
        TRUE                ~ sprintf("%.1f / %.1f",   mean_carrier, mean_control)
      ),
      col_ratio = case_when(
        is_header                                      ~ "",
        !is.na(ratio_nc) & ratio_nc                   ~ sprintf("NC (NC\u2013%.2f)",
                                                                 relative_ci_upper),
        is.na(relative_effect)                        ~ "\u2014",
        TRUE                                          ~ sprintf("%.2f (%.2f\u2013%.2f)",
                                                                 relative_effect,
                                                                 relative_ci_lower,
                                                                 relative_ci_upper)
      ),
      analysis = factor(analysis, levels = analysis)
    )

  n_rows       <- nrow(fd)
  primary_pos  <- which(fd$is_primary)
  data_plot    <- fd %>% filter(!is_header, !is.na(relative_effect))
  data_nc      <- fd %>% filter(!is_header, !is.na(ratio_nc) & ratio_nc)

  p <- ggplot(fd, aes(y = analysis)) +
    geom_vline(xintercept = 1.0, linetype = "dashed", colour = "gray40",
               linewidth = 0.6)

  for (pos in primary_pos) {
    p <- p + annotate("rect",
                      ymin = pos - 0.5, ymax = pos + 0.5,
                      xmin = x_min, xmax = x_max,
                      fill = "gray92", alpha = 1)
  }

  p <- p +
    geom_errorbarh(
      data = data_plot,
      aes(xmin = pmin(relative_ci_lower, forest_max),
          xmax = pmin(relative_ci_upper, forest_max),
          colour = point_color),
      height = 0.25, linewidth = 0.7
    ) +
    geom_point(
      data = data_plot,
      aes(x = pmin(relative_effect, forest_max), colour = point_color),
      size = 3, shape = 18
    )

  if (nrow(data_nc) > 0) {
    p <- p +
      geom_segment(data = data_nc,
                   aes(x = 0.06, xend = pmin(relative_ci_upper, forest_max),
                       y = analysis, yend = analysis, colour = point_color),
                   linewidth = 0.7) +
      geom_segment(data = data_nc,
                   aes(x = 0.06, xend = 0.01,
                       y = analysis, yend = analysis, colour = point_color),
                   arrow = arrow(length = unit(0.15, "cm"), type = "closed"),
                   linewidth = 0.7)
  }

  p <- p +
    scale_colour_identity() +
    geom_text(aes(x = col_n_x,      label = col_n),
              size = 2.5, hjust = 0.5, colour = "black", family = FONT_FAMILY) +
    geom_text(aes(x = col_weight_x, label = col_weight),
              size = 2.5, hjust = 0.5, colour = "black", family = FONT_FAMILY) +
    geom_text(data = fd %>% filter(!is_header),
              aes(x = col_ratio_x, label = col_ratio),
              size = 2.5, hjust = 0.5, colour = "black", family = FONT_FAMILY) +
    scale_x_continuous(
      breaks = seq(0, 1.4, 0.2),
      limits = c(x_min, x_max),
      labels = function(x) formatC(x, digits = 1, format = "f"),
      expand = expansion(mult = 0)
    ) +
    scale_y_discrete(
      labels = setNames(fd$display_label, as.character(fd$analysis)),
      drop   = FALSE
    ) +
    coord_cartesian(xlim = c(x_min, x_max), clip = "off") +
    labs(x = "Response ratio (carrier/control weight loss)", y = NULL) +
    annotate("text", x = col_n_x,      y = n_rows + 0.7,
             label = "n\ncarrier/control", size = 2.4, hjust = 0.5,
             fontface = "bold", colour = "black", family = FONT_FAMILY,
             lineheight = 0.85) +
    annotate("text", x = col_weight_x, y = n_rows + 0.7,
             label = "Weight change (%)\ncarrier/control", size = 2.4,
             hjust = 0.5, fontface = "bold", colour = "black",
             family = FONT_FAMILY, lineheight = 0.85) +
    annotate("text", x = col_ratio_x,  y = n_rows + 0.7,
             label = "Response ratio\n(95% CI)", size = 2.4, hjust = 0.5,
             fontface = "bold", colour = "black", family = FONT_FAMILY,
             lineheight = 0.85) +
    theme_minimal() +
    theme(
      panel.grid.major    = element_blank(),
      panel.grid.minor    = element_blank(),
      panel.background    = element_rect(fill = "white", colour = NA),
      plot.background     = element_rect(fill = "white", colour = NA),
      axis.line.x.bottom  = element_line(colour = "black", linewidth = 0.7),
      axis.line.y.left    = element_blank(),
      panel.border        = element_blank(),
      text                = element_text(size = 9, family = FONT_FAMILY,
                                         colour = "black"),
      axis.text.y         = element_text(
        size = 8, hjust = 0, margin = margin(r = 5),
        face = ifelse(fd$is_header, "bold", "plain")
      ),
      axis.text.x         = element_text(size = 8.5, colour = "black",
                                          margin = margin(t = 5)),
      axis.title.x        = element_text(size = 9.5, face = "bold",
                                          margin = margin(t = 10)),
      axis.ticks.x        = element_line(colour = "black", linewidth = 0.4),
      axis.ticks.y        = element_blank(),
      axis.ticks.length.x = unit(0.15, "cm"),
      plot.margin         = margin(10, 140, 10, 10)
    )

  p
}


