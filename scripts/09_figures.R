###############################################################################

# Create one violin panel for a single drug (matches Fig 1B style from manuscript)
create_violin_panel <- function(matched_df, carrier_var, drug_name, gene_label = "GLP1R") {
  color_carrier <- COLORS$pink
  color_control <- COLORS$green

  plot_data <- matched_df %>%
    filter(drug == tolower(drug_name)) %>%
    mutate(
      group = if_else(.data[[carrier_var]] == 1, "Carriers", "Matched controls"),
      group = factor(group, levels = c("Carriers", "Matched controls"))
    )

  if (nrow(plot_data) == 0) return(NULL)

  group_means <- plot_data %>%
    group_by(group) %>%
    summarise(
      mean_wt = weighted.mean(outcome_weight_pct_change, weights_att, na.rm = TRUE),
      .groups = "drop"
    )

  n_c <- sum(plot_data[[carrier_var]] == 1, na.rm = TRUE)
  n_k <- sum(plot_data[[carrier_var]] == 0, na.rm = TRUE)
  x_labels <- c(paste0("Carriers\n(n=", n_c, ")"),
                paste0("Matched controls\n(n=", n_k, ")"))

  ggplot(plot_data, aes(x = group, y = outcome_weight_pct_change, fill = group)) +
    geom_violin(alpha = 0.4, scale = "width", trim = TRUE,
                colour = "black", linewidth = 0.4, adjust = 1.2) +
    geom_boxplot(width = 0.15, alpha = 0.9, outlier.shape = NA,
                 colour = "black", linewidth = 0.6) +
    geom_jitter(width = 0.08, size = 1.5, alpha = 0.5, colour = "gray10") +
    geom_point(data = group_means,
               aes(x = group, y = mean_wt),
               shape = 23, size = 4, fill = "white", colour = "black",
               stroke = 1.5, inherit.aes = FALSE) +
    geom_text(data = group_means,
              aes(x = group, y = mean_wt,
                  label = sprintf("%.1f%%", mean_wt)),
              hjust = -0.45, size = 3.2, family = FONT_FAMILY,
              fontface = "bold", colour = "black", inherit.aes = FALSE) +
    scale_fill_manual(values = c("Carriers"        = color_carrier,
                                 "Matched controls" = color_control)) +
    scale_x_discrete(labels = x_labels) +
    scale_y_continuous(
      name   = if (drug_name == "Semaglutide") "Body weight change (%)" else NULL,
      breaks = c(-30, -20, -10, 0, 10),
      limits = c(-37, 12),
      labels = function(x) ifelse(x > 0, paste0("+", x), as.character(x)),
      expand = expansion(mult = c(0.02, 0.02))
    ) +
    labs(x = NULL, title = paste0(gene_label, ", ", tolower(drug_name))) +
    theme_minimal() +
    theme(
      panel.grid.major  = element_blank(),
      panel.grid.minor  = element_blank(),
      panel.background  = element_rect(fill = "white", colour = NA),
      plot.background   = element_rect(fill = "white", colour = NA),
      panel.border      = element_rect(fill = NA, colour = "black", linewidth = 0.8),
      text              = element_text(size = 11, family = FONT_FAMILY, colour = "black"),
      axis.text         = element_text(size = 10, colour = "black"),
      axis.text.x       = element_text(size = 10, face = "bold", lineheight = 1.1),
      axis.title        = element_text(size = 11, face = "bold"),
      axis.title.y      = if (drug_name == "Semaglutide")
                            element_text(margin = margin(r = 10)) else element_blank(),
      axis.line         = element_blank(),
      axis.ticks        = element_line(colour = "black", linewidth = 0.5),
      axis.ticks.length = unit(0.15, "cm"),
      plot.title        = element_text(size = 12, face = "bold", hjust = 0.5,
                                       colour = "black"),
      legend.position   = "none",
      plot.margin       = margin(15, 15, 10, 10)
    )
}

