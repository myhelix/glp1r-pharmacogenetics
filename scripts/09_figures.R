make_variant_consequence <- function(consequence) {
  case_when(
    consequence == "missense_variant"       ~ "Missense",
    consequence == "frameshift_variant"     ~ "Frameshift",
    consequence == "inframe_deletion"       ~ "Inframe deletion",
    consequence == "inframe_insertion"      ~ "Inframe insertion",
    consequence == "stop_gained"            ~ "Nonsense",
    consequence == "stop_lost"              ~ "Stop lost",
    consequence == "start_lost"             ~ "Start lost",
    consequence == "splice_donor_variant"   ~ "Splice donor",
    consequence == "splice_acceptor_variant" ~ "Splice acceptor",
    TRUE                                    ~ consequence
  )
}

