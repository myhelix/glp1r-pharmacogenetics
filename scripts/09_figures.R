# Helper: compute mean(SD) or n(%) with optional ATT weights
t1_stats <- function(data, var, weighted = TRUE, weights_var = "weights_att",
                     group_var, default = "\u2014") {
  tryCatch({
    if (!var %in% names(data)) return(list(carrier = default, control = default))
    c_dat <- data[data[[group_var]] == 1, ]
    k_dat <- data[data[[group_var]] == 0, ]
    w_c   <- if (weighted && weights_var %in% names(c_dat)) c_dat[[weights_var]] else rep(1, nrow(c_dat))
    w_k   <- if (weighted && weights_var %in% names(k_dat)) k_dat[[weights_var]] else rep(1, nrow(k_dat))
    if (is.numeric(data[[var]])) {
      m_c <- weighted.mean(c_dat[[var]], w_c, na.rm = TRUE)
      s_c <- sqrt(weighted.mean((c_dat[[var]] - m_c)^2, w_c, na.rm = TRUE))
      m_k <- weighted.mean(k_dat[[var]], w_k, na.rm = TRUE)
      s_k <- sqrt(weighted.mean((k_dat[[var]] - m_k)^2, w_k, na.rm = TRUE))
      list(carrier = sprintf("%.1f (%.1f)", m_c, s_c),
           control = sprintf("%.1f (%.1f)", m_k, s_k))
    } else {
      ref   <- sort(unique(na.omit(data[[var]])))[1]
      n_c   <- sum(c_dat[[var]] == ref, na.rm = TRUE)
      n_k   <- sum(k_dat[[var]] == ref, na.rm = TRUE)
      pct_c <- 100 * sum(w_c[c_dat[[var]] == ref], na.rm = TRUE) / sum(w_c, na.rm = TRUE)
      pct_k <- 100 * sum(w_k[k_dat[[var]] == ref], na.rm = TRUE) / sum(w_k, na.rm = TRUE)
      list(carrier = sprintf("%d (%.1f)", n_c, pct_c),
           control = sprintf("%d (%.1f)", n_k, pct_k))
    }
  }, error = function(e) list(carrier = default, control = default))
}

# Inline SMD for variables not in balance_summary
t1_smd_inline <- function(data, var, group_var, weighted = FALSE,
                           weights_var = "weights_att") {
  tryCatch({
    if (!var %in% names(data)) return("")
    c_dat <- data[data[[group_var]] == 1, ]
    k_dat <- data[data[[group_var]] == 0, ]
    w_k   <- if (weighted && weights_var %in% names(k_dat)) k_dat[[weights_var]] else rep(1, nrow(k_dat))
    x_c   <- as.numeric(c_dat[[var]])
    x_k   <- as.numeric(k_dat[[var]])
    m_c   <- mean(x_c, na.rm = TRUE)
    m_k   <- if (weighted) weighted.mean(x_k, w_k, na.rm = TRUE) else mean(x_k, na.rm = TRUE)
    v_c   <- mean((x_c - m_c)^2, na.rm = TRUE)
    v_k   <- if (weighted) weighted.mean((x_k - m_k)^2, w_k, na.rm = TRUE) else mean((x_k - m_k)^2, na.rm = TRUE)
    ps    <- sqrt((v_c + v_k) / 2)
    if (is.na(ps) || ps == 0) return("0.000")
    sprintf("%.3f", abs(m_c - m_k) / ps)
  }, error = function(e) "")
}

# Get post-match SMD from balance_summary
get_bal_smd <- function(analysis_label, var) {
  tryCatch({
    val <- balance_summary %>%
      filter(analysis == analysis_label, variable == var) %>%
      pull(smd)
    if (length(val) == 0 || all(is.na(val))) return("")
    sprintf("%.3f", abs(val[1]))
  }, error = function(e) "")
}

make_row_t1 <- function(label, pre_c = "\u2014", pre_k = "\u2014", smd_pre = "",
                         post_c, post_k, smd_post = "") {
  list(Variable = label, `Carriers - Pre` = pre_c, `Non-Carriers - Pre` = pre_k,
       `SMD - Pre` = smd_pre, `Carriers - Post` = post_c,
       `Controls - Post` = post_k, `SMD - Post` = smd_post)
}
header_t1 <- function(label) make_row_t1(label, post_c = "", post_k = "")

build_table1 <- function(prematch_df, matched_df, carrier_var,
                          bal_label, gene_label) {

  n_c_pre  <- sum(prematch_df[[carrier_var]] == 1, na.rm = TRUE)
  n_k_pre  <- sum(prematch_df[[carrier_var]] == 0, na.rm = TRUE)
  n_c_post <- sum(matched_df[[carrier_var]]  == 1, na.rm = TRUE)
  n_k_post <- sum(matched_df[[carrier_var]]  == 0, na.rm = TRUE)

  rows <- list()
  r <- 1

  rows[[r]] <- make_row_t1("N",
    as.character(n_c_pre), as.character(n_k_pre), "",
    as.character(n_c_post), as.character(n_k_post), "")
  r <- r + 1

  rows[[r]] <- header_t1("Demographics"); r <- r + 1

  # Age
  pre  <- t1_stats(prematch_df, "age", weighted = FALSE, group_var = carrier_var)
  post <- t1_stats(matched_df,  "age", group_var = carrier_var)
  rows[[r]] <- make_row_t1("  Age, years",
    pre$carrier, pre$control, t1_smd_inline(prematch_df, "age", carrier_var),
    post$carrier, post$control, get_bal_smd(bal_label, "age"))
  r <- r + 1

  # Sex (Female; "F" is alphabetically first)
  pre  <- t1_stats(prematch_df, "sex", weighted = FALSE, group_var = carrier_var)
  post <- t1_stats(matched_df,  "sex", group_var = carrier_var)
  rows[[r]] <- make_row_t1("  Female, n (%)",
    pre$carrier, pre$control, t1_smd_inline(prematch_df, "sex", carrier_var),
    post$carrier, post$control, get_bal_smd(bal_label, "sex"))
  r <- r + 1

  # Genetic similarity — header then one row per level
  rows[[r]] <- make_row_t1("  Genetic similarity, n (%)",
    post_c = "", post_k = ""); r <- r + 1

  anc_levels <- c("European", "African", "Americas", "EastAsian", "SouthAsian", "Other")
  anc_labels <- c("    European", "    African", "    Americas",
                  "    East Asian", "    South Asian", "    Other")
  for (i in seq_along(anc_levels)) {
    anc <- anc_levels[i]
    # Pre
    c_n_pre <- sum(prematch_df[[carrier_var]] == 1 & prematch_df$ancestry_group == anc, na.rm = TRUE)
    k_n_pre <- sum(prematch_df[[carrier_var]] == 0 & prematch_df$ancestry_group == anc, na.rm = TRUE)
    # Post
    c_n_post_a <- sum(matched_df[[carrier_var]] == 1 & matched_df$ancestry_group == anc, na.rm = TRUE)
    k_n_post_a <- sum(matched_df[[carrier_var]] == 0 & matched_df$ancestry_group == anc, na.rm = TRUE)
    w_k_anc    <- sum(matched_df$weights_att[matched_df[[carrier_var]] == 0 &
                        matched_df$ancestry_group == anc], na.rm = TRUE)
    w_k_tot    <- sum(matched_df$weights_att[matched_df[[carrier_var]] == 0], na.rm = TRUE)
    # Inline SMD (binary: this ancestry)
    bin_pre  <- t1_smd_inline(
      prematch_df %>% mutate(.a = as.integer(ancestry_group == anc)), ".a", carrier_var)
    bin_post <- t1_smd_inline(
      matched_df  %>% mutate(.a = as.integer(ancestry_group == anc)), ".a", carrier_var,
      weighted = TRUE)
    rows[[r]] <- make_row_t1(anc_labels[i],
      sprintf("%d (%.1f)", c_n_pre, 100 * c_n_pre / max(n_c_pre, 1)),
      sprintf("%d (%.1f)", k_n_pre, 100 * k_n_pre / max(n_k_pre, 1)),
      bin_pre,
      sprintf("%d (%.1f)", c_n_post_a, 100 * c_n_post_a / max(n_c_post, 1)),
      sprintf("%d (%.1f)", k_n_post_a, 100 * w_k_anc / max(w_k_tot, 1)),
      bin_post)
    r <- r + 1
  }

  rows[[r]] <- header_t1("Baseline Anthropometrics"); r <- r + 1

  # BMI
  pre  <- t1_stats(prematch_df, "bmi_baseline", weighted = FALSE, group_var = carrier_var)
  post <- t1_stats(matched_df,  "bmi_baseline", group_var = carrier_var)
  rows[[r]] <- make_row_t1("  BMI, kg/m\u00b2",
    pre$carrier, pre$control, t1_smd_inline(prematch_df, "bmi_baseline", carrier_var),
    post$carrier, post$control, get_bal_smd(bal_label, "bmi_baseline"))
  r <- r + 1

  # Weight (kg) if available
  wt_var <- intersect(c("weight_baseline_kg", "weight_baseline_value"), names(matched_df))[1]
  if (!is.na(wt_var)) {
    pre  <- t1_stats(prematch_df, wt_var, weighted = FALSE, group_var = carrier_var)
    post <- t1_stats(matched_df,  wt_var, group_var = carrier_var)
    rows[[r]] <- make_row_t1("  Weight, kg",
      pre$carrier, pre$control, t1_smd_inline(prematch_df, wt_var, carrier_var),
      post$carrier, post$control, t1_smd_inline(matched_df, wt_var, carrier_var, weighted = TRUE))
    r <- r + 1
  }

  rows[[r]] <- header_t1("Comorbidities"); r <- r + 1

  # T2D (1 = yes; recode so 1 is ref for stats)
  t2d_pre  <- prematch_df %>% mutate(diabetes_type2 = factor(diabetes_type2, levels = c(1, 0)))
  t2d_post <- matched_df  %>% mutate(diabetes_type2 = factor(diabetes_type2, levels = c(1, 0)))
  pre  <- t1_stats(t2d_pre,  "diabetes_type2", weighted = FALSE, group_var = carrier_var)
  post <- t1_stats(t2d_post, "diabetes_type2", group_var = carrier_var)
  rows[[r]] <- make_row_t1("  Type 2 diabetes, n (%)",
    pre$carrier, pre$control,
    t1_smd_inline(prematch_df %>% mutate(.t = as.integer(diabetes_type2 == 1)), ".t", carrier_var),
    post$carrier, post$control, get_bal_smd(bal_label, "diabetes_type2"))
  r <- r + 1

  # Hypertension (optional)
  if ("hypertension" %in% names(matched_df)) {
    htn_pre  <- prematch_df %>% mutate(hypertension = factor(hypertension, levels = c(1, 0)))
    htn_post <- matched_df  %>% mutate(hypertension = factor(hypertension, levels = c(1, 0)))
    pre  <- t1_stats(htn_pre,  "hypertension", weighted = FALSE, group_var = carrier_var)
    post <- t1_stats(htn_post, "hypertension", group_var = carrier_var)
    rows[[r]] <- make_row_t1("  Hypertension, n (%)",
      pre$carrier, pre$control,
      t1_smd_inline(prematch_df %>% mutate(.h = as.integer(hypertension == 1)), ".h", carrier_var),
      post$carrier, post$control, get_bal_smd(bal_label, "hypertension"))
    r <- r + 1
  }

  rows[[r]] <- header_t1("Treatment Characteristics"); r <- r + 1

  smd_drug_pre  <- t1_smd_inline(prematch_df %>% mutate(.d = as.integer(drug == "semaglutide")), ".d", carrier_var)
  smd_drug_post <- get_bal_smd(bal_label, "drug")

  for (drug_name in c("semaglutide", "tirzepatide")) {
    label_drug <- if (drug_name == "semaglutide") "  Semaglutide, n (%)" else "  Tirzepatide, n (%)"
    label_dose <- if (drug_name == "semaglutide") "    \u22651.7 mg, n (%)" else "    \u226510 mg, n (%)"

    c_n_pre_d  <- sum(prematch_df[[carrier_var]] == 1 & prematch_df$drug == drug_name, na.rm = TRUE)
    k_n_pre_d  <- sum(prematch_df[[carrier_var]] == 0 & prematch_df$drug == drug_name, na.rm = TRUE)
    c_n_post_d <- sum(matched_df[[carrier_var]]  == 1 & matched_df$drug  == drug_name, na.rm = TRUE)
    k_n_post_d <- sum(matched_df[[carrier_var]]  == 0 & matched_df$drug  == drug_name, na.rm = TRUE)
    w_k_d <- sum(matched_df$weights_att[matched_df[[carrier_var]] == 0 &
                   matched_df$drug == drug_name], na.rm = TRUE)

    rows[[r]] <- make_row_t1(label_drug,
      sprintf("%d (%.1f)", c_n_pre_d,  100 * c_n_pre_d  / max(n_c_pre, 1)),
      sprintf("%d (%.1f)", k_n_pre_d,  100 * k_n_pre_d  / max(n_k_pre, 1)),
      smd_drug_pre,
      sprintf("%d (%.1f)", c_n_post_d, 100 * c_n_post_d / max(n_c_post, 1)),
      sprintf("%d (%.1f)", k_n_post_d, 100 * w_k_d / max(w_k_tot, 1)),
      smd_drug_post)
    r <- r + 1

    # High dose (dose_category variable — treat highest category as "high")
    if ("dose_category" %in% names(matched_df)) {
      dose_threshold <- if (drug_name == "semaglutide") "high" else "high"
      pre_drug  <- prematch_df[prematch_df$drug == drug_name, ]
      post_drug <- matched_df[matched_df$drug   == drug_name, ]
      if (nrow(post_drug) > 0 && "dose_category" %in% names(post_drug)) {
        high_levels <- grep("high|2\\.4|10mg|≥", unique(post_drug$dose_category),
                            ignore.case = TRUE, value = TRUE)
        if (length(high_levels) > 0) {
          c_hd_pre  <- sum(pre_drug[[carrier_var]]  == 1 & pre_drug$dose_category  %in% high_levels, na.rm = TRUE)
          k_hd_pre  <- sum(pre_drug[[carrier_var]]  == 0 & pre_drug$dose_category  %in% high_levels, na.rm = TRUE)
          n_c_pre_d_n <- sum(pre_drug[[carrier_var]] == 1, na.rm = TRUE)
          n_k_pre_d_n <- sum(pre_drug[[carrier_var]] == 0, na.rm = TRUE)
          c_hd_post <- sum(post_drug[[carrier_var]] == 1 & post_drug$dose_category %in% high_levels, na.rm = TRUE)
          k_hd_post <- sum(post_drug[[carrier_var]] == 0 & post_drug$dose_category %in% high_levels, na.rm = TRUE)
          rows[[r]] <- make_row_t1(label_dose,
            sprintf("%d (%.1f)", c_hd_pre, 100 * c_hd_pre / max(n_c_pre_d_n, 1)),
            sprintf("%d (%.1f)", k_hd_pre, 100 * k_hd_pre / max(n_k_pre_d_n, 1)),
            "",
            sprintf("%d (%.1f)", c_hd_post, 100 * c_hd_post / max(sum(post_drug[[carrier_var]] == 1, na.rm = TRUE), 1)),
            sprintf("%d (%.1f)", k_hd_post, 100 * k_hd_post / max(sum(post_drug[[carrier_var]] == 0, na.rm = TRUE), 1)),
            "")
          r <- r + 1
        }
      }
    }

    # Prior GLP-1 RA (combined prior_sema_tirz | prior_other_glp1)
    if (all(c("prior_sema_tirz", "prior_other_glp1") %in% names(matched_df))) {
      pre_drug  <- prematch_df %>% filter(drug == drug_name) %>%
        mutate(.pg = as.integer(prior_sema_tirz == 1 | prior_other_glp1 == 1))
      post_drug <- matched_df  %>% filter(drug == drug_name) %>%
        mutate(.pg = as.integer(prior_sema_tirz == 1 | prior_other_glp1 == 1))
      if (nrow(post_drug) > 0) {
        pg_pre  <- t1_stats(pre_drug  %>% mutate(.pg = factor(.pg, levels = c(1,0))), ".pg", weighted = FALSE, group_var = carrier_var)
        pg_post <- t1_stats(post_drug %>% mutate(.pg = factor(.pg, levels = c(1,0))), ".pg", group_var = carrier_var)
        rows[[r]] <- make_row_t1("    Prior GLP-1 RA use, n (%)",
          pg_pre$carrier, pg_pre$control,
          t1_smd_inline(pre_drug, ".pg", carrier_var),
          pg_post$carrier, pg_post$control,
          t1_smd_inline(post_drug, ".pg", carrier_var, weighted = TRUE))
        r <- r + 1
      }
    }
  }

  # Other anti-obesity medication (optional)
  if ("other_anti_obesity_med_baseline" %in% names(matched_df)) {
    aom_pre  <- prematch_df %>% mutate(other_anti_obesity_med_baseline = factor(other_anti_obesity_med_baseline, levels = c(1, 0)))
    aom_post <- matched_df  %>% mutate(other_anti_obesity_med_baseline = factor(other_anti_obesity_med_baseline, levels = c(1, 0)))
    pre  <- t1_stats(aom_pre,  "other_anti_obesity_med_baseline", weighted = FALSE, group_var = carrier_var)
    post <- t1_stats(aom_post, "other_anti_obesity_med_baseline", group_var = carrier_var)
    rows[[r]] <- make_row_t1("  Other anti-obesity medication, n (%)",
      pre$carrier, pre$control, "",
      post$carrier, post$control, "")
    r <- r + 1
  }

  # Follow-up duration (months)
  prematch_df2 <- prematch_df %>% mutate(.fu_mo = followup_duration / 30.44)
  matched_df2  <- matched_df  %>% mutate(.fu_mo = followup_duration / 30.44)
  pre  <- t1_stats(prematch_df2, ".fu_mo", weighted = FALSE, group_var = carrier_var)
  post <- t1_stats(matched_df2,  ".fu_mo", group_var = carrier_var)
  rows[[r]] <- make_row_t1("  Follow-up duration, months",
    pre$carrier, pre$control, t1_smd_inline(prematch_df2, ".fu_mo", carrier_var),
    post$carrier, post$control, get_bal_smd(bal_label, "followup_duration"))

  bind_rows(rows)
}

