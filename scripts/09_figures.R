# FIGURE 1d — GLP1R SLOPEGRAPH
#
# Each line connects one carrier's weight change to the weighted mean weight
# change of their matched controls (within the same MatchIt subclass).
# Lines are coloured by variant class.
###############################################################################

# Variant class colors for slopegraph (matches Fig 1C in original manuscript)
slopegraph_colors <- c(
  "pLoF"              = COLORS$plof,
  "Damaging missense" = COLORS$damaging_missense,
  "rs146868158"       = COLORS$rs146868158,
  "Uncertain missense" = COLORS$green    # green for uncertain in slopegraph
)

create_slopegraph <- function(matched_df, drug_name, carrier_var = "carrier_primary",
                              variant_df     = variant_glp1r,
                              lof_col        = "has_lof",
                              dam_col        = "has_damaging_missense",
                              rs146_col      = "has_rs146",
                              unc_col        = "has_uncertain_missense",
                              gene_label     = "GLP1R") {
  drug_lc <- tolower(drug_name)

  carriers <- matched_df %>%
    filter(.data[[carrier_var]] == 1, drug == drug_lc) %>%
    select(person_source_value, carrier_wt = outcome_weight_pct_change, subclass)

  if (nrow(carriers) == 0) return(NULL)

  ctrl_means <- matched_df %>%
    filter(.data[[carrier_var]] == 0, drug == drug_lc) %>%
    group_by(subclass) %>%
    summarise(ctrl_mean_wt = weighted.mean(outcome_weight_pct_change, weights_att,
                                            na.rm = TRUE),
              .groups = "drop")

  # Select variant annotation columns that exist
  vcols <- c("person_source_value",
             lof_col, dam_col,
             if (!is.null(rs146_col)) rs146_col,
             unc_col)
  vcols <- intersect(vcols, names(variant_df))

  # Build factor levels for variant_type based on columns available
  vt_levels <- c("pLoF", "Damaging missense")
  if (!is.null(rs146_col) && rs146_col %in% names(variant_df)) {
    vt_levels <- c(vt_levels, "rs146868158")
  }
  vt_levels <- c(vt_levels, "Uncertain missense")

  joined <- carriers %>%
    left_join(ctrl_means, by = "subclass") %>%
    left_join(variant_df %>% select(all_of(vcols)), by = "person_source_value")

  has_rs146_col <- !is.null(rs146_col) && rs146_col %in% names(joined)

  if (has_rs146_col) {
    joined <- joined %>% mutate(
      variant_type = case_when(
        .data[[lof_col]]   == 1 ~ "pLoF",
        .data[[dam_col]]   == 1 ~ "Damaging missense",
        !is.na(.data[[rs146_col]]) & .data[[rs146_col]] == 1 ~ "rs146868158",
        .data[[unc_col]]   == 1 ~ "Uncertain missense",
        TRUE                    ~ "Uncertain missense"
      )
    )
  } else {
    joined <- joined %>% mutate(
      variant_type = case_when(
        .data[[lof_col]] == 1 ~ "pLoF",
        .data[[dam_col]] == 1 ~ "Damaging missense",
        .data[[unc_col]] == 1 ~ "Uncertain missense",
        TRUE                  ~ "Uncertain missense"
      )
    )
  }

  slope_df <- joined %>%
    mutate(
